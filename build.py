#!/usr/bin/env python3
"""Build the single-file app from src/.

Usage:
    python build.py

The generated root index.html is the file GitHub Pages serves and the file
that can be opened offline. Edit files under src/, then run this script.
"""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent
SRC = ROOT / 'src'
OUT = ROOT / 'index.html'


def read(rel: str) -> str:
    return (SRC / rel).read_text(encoding='utf-8')


def inline_css(match: re.Match) -> str:
    href = match.group(1)
    if href.startswith(('http://', 'https://', '//')):
        return match.group(0)
    css = read(href)
    return f'<style data-src="{href}">\n{css}\n</style>'


def inline_js(match: re.Match) -> str:
    src = match.group(1)
    if src.startswith(('http://', 'https://', '//')):
        return match.group(0)
    js = read(src)
    return f'<script data-src="{src}">\n{js}\n</script>'


def main() -> int:
    html = read('index.html')
    html = re.sub(r'<link\s+rel="stylesheet"\s+href="([^"]+)"\s*/?>', inline_css, html)
    html = re.sub(r'<script\s+src="([^"]+)"\s*>\s*</script>', inline_js, html)
    html = html.replace(
        '<!DOCTYPE html>',
        '<!DOCTYPE html>\n<!-- Generated from src/ by build.py. Do not edit this file directly. -->',
        1,
    )
    OUT.write_text(html, encoding='utf-8', newline='\n')
    size_kb = OUT.stat().st_size / 1024
    print(f'Built {OUT} ({size_kb:.1f} KB)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
